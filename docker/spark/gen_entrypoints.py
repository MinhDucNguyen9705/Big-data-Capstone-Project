"""Write one SparkApplication entrypoint per job: /opt/cryptopipe/jobs/<name>.py -> cryptopipe.jobs.<name>.main.

Build-time helper for docker/spark/Dockerfile (owner A). Reads the registry `cryptopipe.jobs.JOBS`, so a job
added there gets its `local:///opt/cryptopipe/jobs/<name>.py` file on the next image build.
"""

from __future__ import annotations

import sys
from pathlib import Path

from cryptopipe.jobs import JOBS

TEMPLATE = '''"""Entrypoint for {module}.main (owner {owner}). Generated by docker/spark/gen_entrypoints.py."""

import sys

from {module} import main

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''


def main(out_dir: str) -> int:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for name, (module, owner, _task) in JOBS.items():
        (out / f"{name}.py").write_text(TEMPLATE.format(module=module, owner=owner))
        print(f"local://{out}/{name}.py -> {module}.main")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
