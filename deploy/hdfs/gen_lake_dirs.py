"""Generate the list of HDFS lake folders from `cryptopipe.contracts.LAKE_PATHS`. Owner: A (Platform).

The init-lake Job (deploy/hdfs/base/init-lake-job.yaml) creates every folder in the list, owned by `spark`.
Parent folders are listed too, so every level gets the same owner and mode.

    python deploy/hdfs/gen_lake_dirs.py            # rewrite deploy/hdfs/base/lake-dirs.generated.txt
    python deploy/hdfs/gen_lake_dirs.py --check    # exit 1 if the committed file is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path, PurePosixPath

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from cryptopipe.contracts import LAKE_PATHS  # noqa: E402  (read only)

OUT = Path(__file__).parent / "base" / "lake-dirs.generated.txt"
LAKE = "/lake"  # path part of CRYPTO_LAKE_ROOT in deploy/common/cryptopipe-env.yaml
EXTRA = ["/spark-events", "/user/spark"]  # Spark event logs (History Server) and the spark user's home


def lake_dirs() -> list[str]:
    dirs = set(EXTRA) | {LAKE}
    for rel in LAKE_PATHS.values():
        path = PurePosixPath(LAKE) / rel
        dirs.update(str(p) for p in [path, *path.parents] if str(p) != "/")
    return sorted(dirs)


def render() -> str:
    header = "# GENERATED by deploy/hdfs/gen_lake_dirs.py from contracts.LAKE_PATHS. Do not edit by hand.\n"
    return header + "\n".join(lake_dirs()) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed file differs")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date with contracts.py; run python deploy/hdfs/gen_lake_dirs.py")
            return 1
        print(f"{OUT} matches contracts.py")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(lake_dirs())} folders)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
