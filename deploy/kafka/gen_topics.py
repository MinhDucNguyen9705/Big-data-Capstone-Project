"""Generate Strimzi KafkaTopic manifests from `cryptopipe.contracts.TOPICS`. Owner: A (Platform).

Topic names, partitions and cleanup policy come only from the contract, so the cluster cannot drift from what
B, C and D import. Replicas depend on the deploy profile.

    python deploy/kafka/gen_topics.py                    # rewrite deploy/kafka/topics.generated.yaml (local)
    python deploy/kafka/gen_topics.py --check            # exit 1 if the committed file is out of date
    python deploy/kafka/gen_topics.py --profile cloud -o -   # print the cloud variant (RF 3) to stdout
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from cryptopipe.contracts import TOPICS, Topic  # noqa: E402  (read only)

OUT = Path(__file__).with_name("topics.generated.yaml")
CLUSTER = "crypto"
NAMESPACE = "kafka"
REPLICAS = {"local": 1, "lite": 1, "cloud": 3}


def resource_name(topic: str) -> str:
    """K8s names allow only [a-z0-9-.]; the real topic name goes in spec.topicName."""
    return re.sub(r"[^a-z0-9-]", "-", topic.lower())


def topic_manifest(topic: Topic, replicas: int) -> str:
    config = {"cleanup.policy": "compact" if topic.compacted else "delete"}
    if topic.retention_ms is not None:
        config["retention.ms"] = str(topic.retention_ms)
    config_lines = "".join(f'    {k}: "{v}"\n' for k, v in config.items())
    return (
        "apiVersion: kafka.strimzi.io/v1\n"
        "kind: KafkaTopic\n"
        "metadata:\n"
        f"  name: {resource_name(topic.name)}\n"
        f"  namespace: {NAMESPACE}\n"
        "  labels:\n"
        f"    strimzi.io/cluster: {CLUSTER}\n"
        "    app.kubernetes.io/part-of: crypto-pipeline\n"
        "spec:\n"
        f"  topicName: {topic.name}\n"
        f"  partitions: {topic.partitions}\n"
        f"  replicas: {replicas}\n"
        "  config:\n"
        f"{config_lines}"
    )


def render(profile: str) -> str:
    header = (
        "# GENERATED by deploy/kafka/gen_topics.py from src/cryptopipe/contracts.py. Do not edit by hand.\n"
        f"# Profile: {profile} (replicas {REPLICAS[profile]}). Regenerate: python deploy/kafka/gen_topics.py\n"
    )
    return header + "---\n".join(topic_manifest(t, REPLICAS[profile]) for t in TOPICS)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--profile", choices=sorted(REPLICAS), default="local")
    parser.add_argument("-o", "--output", default=str(OUT), help="output file, or - for stdout")
    parser.add_argument("--check", action="store_true", help="fail if the output file differs from the contract")
    args = parser.parse_args(argv)

    text = render(args.profile)
    if args.check:
        current = Path(args.output).read_text(encoding="utf-8") if Path(args.output).exists() else ""
        if current != text:
            print(f"{args.output} is out of date with contracts.py; run python deploy/kafka/gen_topics.py")
            return 1
        print(f"{args.output} matches contracts.py ({len(TOPICS)} topics)")
        return 0
    if args.output == "-":
        sys.stdout.write(text)
    else:
        Path(args.output).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {args.output} ({len(TOPICS)} topics, profile {args.profile})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
